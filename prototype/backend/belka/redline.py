"""red-line gate: ตรวจข้อความการตลาดด้วยกฎที่เขียนเป็นโค้ด (ไม่เรียก AI).

ใช้สองที่:
1. เป็นเครื่องมือ check_redline ที่เอเจนต์เรียกระหว่างเขียนแคปชัน (R11)
2. ตรวจซ้ำทุกแคปชันใน planner ก่อนส่งถึงร้าน (defense in depth)
"""
from __future__ import annotations

import re

from .models import RedlineIssue, RedlineResult

# (คำ, เหตุผล, คำแนะนำ)
_TERMS: list[tuple[str, str, str]] = [
    ("การันตี", "สัญญาผลลัพธ์ที่ร้านควบคุมไม่ได้", "เล่าสิ่งที่ร้านทำจริง เช่น วัตถุดิบหรือวิธีทำ"),
    ("รับประกัน", "สัญญาผลลัพธ์ที่ร้านควบคุมไม่ได้", "เล่าสิ่งที่ร้านทำจริง เช่น วัตถุดิบหรือวิธีทำ"),
    ("ที่สุด", "คำเกินจริงที่ตรวจสอบไม่ได้", "ตัดคำว่า 'ที่สุด' แล้วบอกจุดเด่นที่ตรวจสอบได้"),
    ("อันดับ 1", "อ้างอันดับโดยไม่มีแหล่งอ้างอิง", "ตัดออก หรือใช้คำว่า 'เมนูที่ลูกค้าสั่งบ่อย'"),
    ("อันดับหนึ่ง", "อ้างอันดับโดยไม่มีแหล่งอ้างอิง", "ตัดออก หรือใช้คำว่า 'เมนูที่ลูกค้าสั่งบ่อย'"),
    ("100%", "สัญญาผลลัพธ์ที่ตรวจสอบไม่ได้", "ตัดตัวเลขออก"),
    ("แน่นอน", "สัญญาผลลัพธ์", "ใช้คำชวน เช่น 'ลองแวะมาชิม'"),
    ("ไม่อร่อยยินดีคืนเงิน", "สัญญาที่ร้านอาจทำไม่ได้จริง", "ตัดออก เว้นแต่ร้านมีนโยบายนี้จริง"),
    ("หายขาด", "อ้างผลด้านสุขภาพ", "ตัดออก ห้ามอ้างผลด้านสุขภาพ"),
    ("ลดน้ำหนัก", "อ้างผลด้านสุขภาพ", "ตัดออก ห้ามอ้างผลด้านสุขภาพ"),
    ("รักษาโรค", "อ้างผลด้านสุขภาพ", "ตัดออก ห้ามอ้างผลด้านสุขภาพ"),
]

# ตัวเลขผลลัพธ์ เช่น "ยอดขายเพิ่ม 50%" หรือ "กำไรโต 2 เท่า"
_RESULT_CLAIM = re.compile(r"(เพิ่ม|ลด|โต|ขึ้น)\S{0,12}\s*\d+(?:\.\d+)?\s*(%|เปอร์เซ็นต์|เท่า)")
# ความขาดแคลนเร่งรัด เช่น "เหลือ 3 แก้วสุดท้าย"
_SCARCITY = re.compile(r"เหลือ(?:เพียง|แค่)?\s*\d+\s*(ที่|ชิ้น|แก้ว|จาน|กล่อง|ที่นั่ง)")


def check_redline(text: str) -> RedlineResult:
    """ตรวจข้อความ คืนค่า passed และรายการปัญหาพร้อมคำแนะนำ."""
    issues: list[RedlineIssue] = []
    if not text or not text.strip():
        issues.append(RedlineIssue(term="", reason="ข้อความว่าง", suggestion="เขียนแคปชันอย่างน้อย 1 ประโยค"))
        return RedlineResult(passed=False, issues=issues)

    for term, reason, suggestion in _TERMS:
        if term in text:
            issues.append(RedlineIssue(term=term, reason=reason, suggestion=suggestion))

    match = _RESULT_CLAIM.search(text)
    if match:
        issues.append(
            RedlineIssue(
                term=match.group(0),
                reason="ตัวเลขผลลัพธ์ที่ไม่มีแหล่งอ้างอิง",
                suggestion="ตัดตัวเลขออก AI ห้ามสร้างตัวเลขผลลัพธ์",
            )
        )

    match = _SCARCITY.search(text)
    if match:
        issues.append(
            RedlineIssue(
                term=match.group(0),
                reason="เร่งให้ซื้อด้วยความขาดแคลน ต้องเป็นจริงเท่านั้น",
                suggestion="ตัดออก หรือให้เจ้าของร้านยืนยันว่าเป็นจริงก่อนโพสต์",
            )
        )

    return RedlineResult(passed=not issues, issues=issues)
